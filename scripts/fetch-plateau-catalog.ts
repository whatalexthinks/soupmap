/**
 * Pulls the PLATEAU data catalog and writes src/data/plateau-tilesets.json:
 * one building 3D Tiles tileset per municipality (or ward) code that has a shop.
 *
 *   npm run data:plateau            # fail loudly if the catalog can't be fetched
 *   npm run data:plateau -- --soft  # keep the last snapshot instead (used by `npm run build`)
 *
 * Choice per code: LOD2 over LOD1 (LOD3+ is patchy and heavy), untextured over textured
 * (we restyle buildings, so textures would be wasted bandwidth), newest data first.
 *
 * Catalog docs: https://docs.plateauview.mlit.go.jp (the API schema may change without notice).
 * Override the endpoint with PLATEAU_CATALOG_URL (e.g. for a mirror or a test fixture).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";
import { color, describeError, fetchWithTimeout, loadShops, parseArgs } from "./lib/util.ts";

const CATALOG_URL = process.env.PLATEAU_CATALOG_URL ?? "https://api.plateauview.mlit.go.jp/datacatalog/plateau-datasets";
const OUT = new URL("../src/data/plateau-tilesets.json", import.meta.url);

const Dataset = z.looseObject({
  id: z.string().optional(),
  name: z.string().optional(),
  city: z.string().nullish(),
  city_code: z.string().nullish(),
  ward: z.string().nullish(),
  ward_code: z.string().nullish(),
  type_en: z.string().nullish(),
  format: z.string().nullish(),
  url: z.string(),
  lod: z.union([z.string(), z.number()]).nullish(),
  texture: z.boolean().nullish(),
  year: z.number().nullish(),
  registration_year: z.number().nullish(),
});
type Dataset = z.infer<typeof Dataset>;
const Catalog = z.looseObject({ datasets: z.array(z.unknown()) });

export interface TilesetRef {
  cityCode: string;
  name: string;
  lod: string;
  texture: boolean;
  year: number | null;
  url: string;
}

const args = parseArgs(process.argv.slice(2));
const soft = args.soft === true;
const timeoutMs = Number(args.timeout ?? 60_000);

function isUntextured(d: Dataset): boolean {
  return d.texture === false || /no_texture/i.test(`${d.id ?? ""} ${d.url}`);
}

/** Higher is better. */
function score(d: Dataset): number {
  const lod = Number(d.lod ?? 0);
  const lodScore = lod === 2 ? 300 : lod === 1 ? 200 : lod >= 3 ? 100 : 0;
  return lodScore + (isUntextured(d) ? 50 : 0) + ((d.year ?? 0) - 2000) / 100 + ((d.registration_year ?? 0) - 2000) / 1000;
}

async function main(): Promise<void> {
  const shops = loadShops();
  const codes = [...new Set(shops.map((s) => s.cityCode))].sort();

  console.log(`Fetching PLATEAU catalog (${CATALOG_URL}) …`);
  const response = await fetchWithTimeout(CATALOG_URL, { timeoutMs, headers: { accept: "application/json" } });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const catalog = Catalog.parse(await response.json());

  const buildings: Dataset[] = [];
  for (const raw of catalog.datasets) {
    const parsed = Dataset.safeParse(raw);
    if (!parsed.success) continue;
    const d = parsed.data;
    if (d.type_en === "bldg" && /3d ?tiles/i.test(d.format ?? "") && /tileset\.json/.test(d.url)) buildings.push(d);
  }
  console.log(`  ${catalog.datasets.length} datasets, ${buildings.length} building 3D Tiles`);

  const tilesets: TilesetRef[] = [];
  for (const code of codes) {
    const matches = buildings.filter((d) => d.ward_code === code || d.city_code === code);
    const best = matches.sort((a, b) => score(b) - score(a))[0];
    const shopsHere = shops.filter((s) => s.cityCode === code).map((s) => s.slug).join(", ");
    if (!best) {
      console.log(color.dim(`  ${code}: no building tileset (${shopsHere})`));
      continue;
    }
    const ref: TilesetRef = {
      cityCode: code,
      name: [best.city, best.ward].filter(Boolean).join(" ") || best.name || code,
      lod: String(best.lod ?? "?"),
      texture: !isUntextured(best),
      year: best.year ?? null,
      url: best.url,
    };
    tilesets.push(ref);
    console.log(`  ${code}: ${ref.name} LOD${ref.lod}${ref.texture ? "" : " (no texture)"} ${ref.year ?? ""} ${color.dim(`(${shopsHere})`)}`);
  }

  const out = {
    generatedAt: new Date().toISOString(),
    source: CATALOG_URL,
    note: "Generated by scripts/fetch-plateau-catalog.ts. Do not edit by hand.",
    tilesets,
  };
  writeFileSync(OUT, `${JSON.stringify(out, null, 2)}\n`);
  console.log(color.green(`✔ wrote ${tilesets.length} tileset(s) to src/data/plateau-tilesets.json`));
}

main().catch((error: unknown) => {
  const message = describeError(error);
  if (soft) {
    const kept = existsSync(OUT) ? (JSON.parse(readFileSync(OUT, "utf8")) as { tilesets?: unknown[] }).tilesets?.length ?? 0 : 0;
    console.warn(color.yellow(`⚠ PLATEAU catalog unavailable (${message}). Keeping the existing snapshot (${kept} tileset(s)).`));
    console.warn(color.yellow("  Building info only works for cities in that snapshot. The rest of the build is unaffected."));
    process.exit(0);
  }
  console.error(color.red(`✖ PLATEAU catalog fetch failed: ${message}`));
  process.exit(1);
});
